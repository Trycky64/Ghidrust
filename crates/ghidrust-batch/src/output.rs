//! Streaming output writers for batch decompilation results.

use crate::engine::FunctionOutcome;
use serde::Serialize;
use std::collections::HashSet;
use std::fs::{File, OpenOptions};
use std::io::{self, BufRead, BufReader, BufWriter, Read, Seek, SeekFrom, Write};
use std::path::{Path, PathBuf};

/// Output format for batch decompilation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OutputFormat {
    /// One JSON object per line (streaming-friendly).
    Jsonl,
    /// Composite C file with all functions.
    CFile,
}

impl OutputFormat {
    pub fn from_str(s: &str) -> Option<Self> {
        match s.to_lowercase().as_str() {
            "jsonl" | "json" => Some(Self::Jsonl),
            "c" | "cfile" => Some(Self::CFile),
            _ => None,
        }
    }
}

/// One JSONL record.
#[derive(Debug, Serialize, serde::Deserialize)]
pub struct JsonlRecord {
    pub address: String,
    pub name: String,
    pub status: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub partial_reason: Option<String>,
    #[serde(default)]
    pub structure_fallback: bool,
    #[serde(default)]
    pub region_count: usize,
    #[serde(default)]
    pub region_construction_cost: usize,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub pseudo_c: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
    pub insn_count: usize,
    pub decompile_us: u128,
    pub goto_count: usize,
    pub leaf_count: usize,
}

/// Streaming output writer.
pub struct OutputWriter {
    format: OutputFormat,
    writer: BufWriter<File>,
    path: PathBuf,
    count: usize,
}

impl OutputWriter {
    /// Open a new output file.
    pub fn open(path: impl Into<PathBuf>, format: OutputFormat) -> io::Result<Self> {
        let path = path.into();
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let file = OpenOptions::new()
            .create(true)
            .write(true)
            .truncate(true)
            .open(&path)?;
        let mut writer = BufWriter::with_capacity(256 * 1024, file);
        if format == OutputFormat::CFile {
            writeln!(writer, "// Ghidrust batch decompilation output")?;
            writeln!(writer, "// Generated by ghidrust batch-decompile\n")?;
        }
        Ok(Self {
            format,
            writer,
            path,
            count: 0,
        })
    }

    /// Open for append (resume mode).
    pub fn open_append(path: impl Into<PathBuf>, format: OutputFormat) -> io::Result<Self> {
        let path = path.into();
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if format == OutputFormat::Jsonl {
            compact_jsonl_for_resume(&path)?;
        }
        let file = OpenOptions::new().create(true).append(true).open(&path)?;
        let writer = BufWriter::with_capacity(256 * 1024, file);
        Ok(Self {
            format,
            writer,
            path,
            count: 0,
        })
    }

    /// Write one function result.
    pub fn write_outcome(&mut self, outcome: &FunctionOutcome) -> io::Result<()> {
        match self.format {
            OutputFormat::Jsonl => {
                let record = JsonlRecord {
                    address: format!("0x{:016x}", outcome.address),
                    name: outcome.name.clone(),
                    status: if outcome.error.is_some() {
                        "error"
                    } else if outcome.partial_reason.is_some() {
                        "partial"
                    } else if outcome.structure_fallback {
                        "unstructured_fallback"
                    } else {
                        "ok"
                    }
                    .to_string(),
                    partial_reason: outcome.partial_reason.clone(),
                    structure_fallback: outcome.structure_fallback,
                    region_count: outcome.region_count,
                    region_construction_cost: outcome.region_construction_cost,
                    pseudo_c: outcome.pseudo_c.clone(),
                    error: outcome.error.clone(),
                    insn_count: outcome.insn_count,
                    decompile_us: outcome.decompile_us,
                    goto_count: outcome.goto_count,
                    leaf_count: outcome.leaf_count,
                };
                serde_json::to_writer(&mut self.writer, &record)
                    .map_err(|e| io::Error::new(io::ErrorKind::Other, e))?;
                writeln!(self.writer)?;
            }
            OutputFormat::CFile => {
                writeln!(
                    self.writer,
                    "// Function: {} @ 0x{:016x}",
                    outcome.name, outcome.address
                )?;
                if let Some(ref code) = outcome.pseudo_c {
                    writeln!(self.writer, "{code}")?;
                } else if let Some(ref err) = outcome.error {
                    writeln!(self.writer, "// ERROR: {err}")?;
                }
                if let Some(reason) = &outcome.partial_reason {
                    writeln!(self.writer, "// PARTIAL: {reason}")?;
                }
                if outcome.structure_fallback {
                    writeln!(
                        self.writer,
                        "// STRUCTURE: complete unstructured CFG fallback"
                    )?;
                }
                writeln!(self.writer)?;
            }
        }
        self.count += 1;
        // Flush every 100 functions to bound memory.
        Ok(())
    }

    pub fn flush(&mut self) -> io::Result<()> {
        self.writer.flush()
    }

    /// Flush and finalize.
    pub fn finish(&mut self) -> io::Result<()> {
        self.writer.flush()
    }

    /// Path to the output file.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Number of records written.
    pub fn count(&self) -> usize {
        self.count
    }
}

/// Read successful JSONL addresses while repairing a crash-truncated final record.
pub fn completed_jsonl_addresses(path: &Path) -> io::Result<HashSet<u64>> {
    if !path.exists() {
        return Ok(HashSet::new());
    }
    repair_jsonl_tail(path)?;
    let reader = BufReader::new(File::open(path)?);
    let mut completed = HashSet::new();
    for line in reader.lines() {
        let line = line?;
        let record: JsonlRecord = serde_json::from_str(&line)
            .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
        if matches!(record.status.as_str(), "ok" | "unstructured_fallback") {
            if let Some(address) = parse_address(&record.address) {
                completed.insert(address);
            }
        }
    }
    Ok(completed)
}

fn parse_address(address: &str) -> Option<u64> {
    u64::from_str_radix(address.trim_start_matches("0x"), 16).ok()
}

/// Remove stale failure rows and duplicate successes before retrying a JSONL
/// output. The original remains intact until the compacted file is flushed and
/// atomically replaces it, so interruption during compaction is recoverable.
fn compact_jsonl_for_resume(path: &Path) -> io::Result<()> {
    if !path.exists() {
        return Ok(());
    }
    repair_jsonl_tail(path)?;

    let mut seen = HashSet::new();
    let mut needs_compaction = false;
    for line in BufReader::with_capacity(1024 * 1024, File::open(path)?).split(b'\n') {
        let line = line?;
        if line.is_empty() {
            continue;
        }
        let record: JsonlRecord = serde_json::from_slice(&line)
            .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
        if matches!(record.status.as_str(), "error" | "partial") {
            needs_compaction = true;
        } else if matches!(record.status.as_str(), "ok" | "unstructured_fallback") {
            if let Some(address) = parse_address(&record.address) {
                if !seen.insert(address) {
                    needs_compaction = true;
                }
            }
        }
    }
    if !needs_compaction {
        return Ok(());
    }

    let mut temp_path = path.to_path_buf();
    temp_path.set_extension("jsonl.resume.tmp");
    let mut output = BufWriter::with_capacity(
        1024 * 1024,
        OpenOptions::new()
            .create(true)
            .truncate(true)
            .write(true)
            .open(&temp_path)?,
    );
    let mut seen_successes = HashSet::new();
    for line in BufReader::with_capacity(1024 * 1024, File::open(path)?).split(b'\n') {
        let line = line?;
        if line.is_empty() {
            continue;
        }
        let record: JsonlRecord = serde_json::from_slice(&line)
            .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
        if matches!(record.status.as_str(), "error" | "partial") {
            continue;
        }
        if matches!(record.status.as_str(), "ok" | "unstructured_fallback") {
            if let Some(address) = parse_address(&record.address) {
                if !seen_successes.insert(address) {
                    continue;
                }
            }
        }
        output.write_all(&line)?;
        output.write_all(b"\n")?;
    }
    output.flush()?;
    output.get_ref().sync_all()?;
    drop(output);
    std::fs::rename(&temp_path, path)?;
    Ok(())
}

fn repair_jsonl_tail(path: &Path) -> io::Result<()> {
    if !path.exists() {
        return Ok(());
    }
    let mut file = OpenOptions::new().read(true).write(true).open(path)?;
    let len = file.metadata()?.len();
    if len == 0 {
        return Ok(());
    }
    file.seek(SeekFrom::End(-1))?;
    let mut last = [0u8; 1];
    file.read_exact(&mut last)?;
    if last[0] == b'\n' {
        return Ok(());
    }
    let mut pos = len;
    while pos > 0 {
        pos -= 1;
        file.seek(SeekFrom::Start(pos))?;
        file.read_exact(&mut last)?;
        if last[0] == b'\n' {
            file.set_len(pos + 1)?;
            return Ok(());
        }
    }
    file.set_len(0)
}

#[cfg(test)]
mod recovery_tests {
    use super::*;

    #[test]
    fn incomplete_final_jsonl_record_is_removed_and_successes_recovered() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("results.jsonl");
        std::fs::write(
            &path,
            "{\"address\":\"0x0000000000001234\",\"name\":\"f\",\"status\":\"ok\",\"insn_count\":1,\"decompile_us\":2,\"goto_count\":0,\"leaf_count\":1}\n{\"address\":",
        ).unwrap();
        let addresses = completed_jsonl_addresses(&path).unwrap();
        assert_eq!(addresses, HashSet::from([0x1234]));
        assert!(std::fs::read_to_string(path).unwrap().ends_with('\n'));
    }

    #[test]
    fn resume_removes_stale_failures_and_deduplicates_successes() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("results.jsonl");
        let success = r#"{"address":"0x0000000000001234","name":"ok","status":"ok","pseudo_c":"return 1;","insn_count":1,"decompile_us":2,"goto_count":0,"leaf_count":1}"#;
        let fallback = r#"{"address":"0x0000000000009876","name":"fallback","status":"unstructured_fallback","structure_fallback":true,"pseudo_c":"goto block_1;","insn_count":3,"decompile_us":2,"goto_count":2,"leaf_count":2}"#;
        let partial = r#"{"address":"0x0000000000007777","name":"partial","status":"partial","partial_reason":"instruction limit reached","pseudo_c":"return ?;","insn_count":4096,"decompile_us":2,"goto_count":0,"leaf_count":1}"#;
        let error = r#"{"address":"0x0000000000005678","name":"retry","status":"error","error":"worker exited","insn_count":0,"decompile_us":2,"goto_count":0,"leaf_count":0}"#;
        std::fs::write(
            &path,
            format!("{success}\n{fallback}\n{partial}\n{error}\n{success}\n"),
        )
        .unwrap();

        let mut output = OutputWriter::open_append(&path, OutputFormat::Jsonl).unwrap();
        output
            .write_outcome(&FunctionOutcome {
                address: 0x5678,
                name: "retry".into(),
                pseudo_c: Some("return 2;".into()),
                error: None,
                partial_reason: None,
                structure_fallback: false,
                region_count: 1,
                region_construction_cost: 1,
                insn_count: 2,
                decompile_us: 3,
                goto_count: 0,
                leaf_count: 1,
            })
            .unwrap();
        output.finish().unwrap();

        let lines: Vec<JsonlRecord> = std::fs::read_to_string(path)
            .unwrap()
            .lines()
            .map(|line| serde_json::from_str(line).unwrap())
            .collect();
        assert_eq!(lines.len(), 3);
        assert_eq!(lines.iter().filter(|row| row.status == "ok").count(), 2);
        assert_eq!(
            lines
                .iter()
                .filter(|row| row.status == "unstructured_fallback")
                .count(),
            1
        );
        assert_eq!(
            lines
                .iter()
                .map(|row| row.address.as_str())
                .collect::<HashSet<_>>()
                .len(),
            3,
            "resume must leave one final row per function address"
        );
    }
}
